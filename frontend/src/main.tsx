import {StrictMode,useEffect} from "react";
import {createRoot} from "react-dom/client";
import {AppProvider,useApp} from "./context";
import {navigate,usePath,Link} from "./router";
import {Layout} from "./components/layout";
import {Empty,Icon,PageHeading} from "./components/ui";
import {Login} from "./pages/auth";
import {Market,ProductDetail} from "./pages/market";
import {Orders,OrderDetail,Billing} from "./pages/orders";
import {Workspace} from "./pages/workspace";
import {SellerNodes,SellerListings,SellerEarnings} from "./pages/seller";
import {Overview} from "./pages/overview";
import {Account} from "./pages/account";
import {ListingReview,AuditLog} from "./pages/operator";
import "./styles.css";
function App(){
 const{user,ready}=useApp();const path=usePath();
 const home=user?.role==="provider"?"/seller/overview":user?.role==="operator"?"/operator/listings":"/buyer/market";
 useEffect(()=>{if(!ready)return;if(!user&&path!=="/login")navigate("/login",true);else if(user&&(path==="/"||path==="/login"))navigate(home,true);},[user,ready,path,home]);
 if(!ready)return <div className="app-loading"><span className="brand-emblem">SX</span><span className="spinner"/>正在连接平台…</div>;
 if(!user)return <Login/>;
 if(path==="/"||path==="/login")return null;
 const prefix=user.role==="provider"?"/seller/":`/${user.role}/`;
 if(!path.startsWith(prefix))return <Layout path={path}><PageHeading title="无法访问此工作台" subtitle="当前账号没有此页面的访问权限。"/><Empty title="账号权限不匹配" text="买家、卖家和运营账号使用各自独立的工作台。" action={<Link className="button primary" to={home}>返回我的工作台<Icon name="arrow" size={16}/></Link>}/></Layout>;
 let content;
 if(path===prefix+"account")content=<Account/>;
 else if(path==="/buyer/overview")content=<Overview/>;
 else if(path==="/buyer/market")content=<Market/>;
 else if(path.startsWith("/buyer/market/"))content=<ProductDetail id={path.split("/")[3]!}/>;
 else if(path==="/buyer/orders")content=<Orders/>;
 else if(path.startsWith("/buyer/orders/"))content=<OrderDetail id={path.split("/")[3]!}/>;
 else if(path==="/buyer/workspace")content=<Workspace/>;
 else if(path==="/buyer/billing")content=<Billing/>;
 else if(path==="/seller/overview")content=<Overview seller/>;
 else if(path==="/seller/nodes")content=<SellerNodes/>;
 else if(path==="/seller/listings")content=<SellerListings/>;
 else if(path==="/seller/orders")content=<Orders seller/>;
 else if(path.startsWith("/seller/orders/"))content=<OrderDetail seller id={path.split("/")[3]!}/>;
 else if(path==="/seller/earnings")content=<SellerEarnings/>;
 else if(path==="/operator/listings")content=<ListingReview/>;
 else if(path==="/operator/orders")content=<Orders operator/>;
 else if(path==="/operator/audit")content=<AuditLog/>;
 else content=<Empty title="页面不存在" text="请通过侧边菜单进入需要的页面。" action={<Link className="button primary" to={home}>返回工作台</Link>}/>;
 return <Layout path={path}>{content}</Layout>;
}
createRoot(document.getElementById("root")!).render(<StrictMode><AppProvider><App/></AppProvider></StrictMode>);
